begin;
select plan(32);

select has_column('public', 'profiles', 'avatar_url', 'profiles can store an avatar URL');
select has_column('public', 'profiles', 'description', 'profiles can store a player description');
select has_table('public', 'alliances', 'alliances are persisted');
select has_table('public', 'alliance_members', 'alliance roles are persisted');
select has_table('public', 'alliance_invitations', 'alliance invitations are persisted');
select has_table('public', 'diplomatic_relations', 'diplomacy is persisted');
select has_table('public', 'private_messages', 'private messages are persisted');
select has_table('public', 'alliance_messages', 'alliance messages are persisted');
select has_table('public', 'multiplayer_notifications', 'private realtime notifications are persisted');
select has_table('app_private', 'realm_rules', 'expansion rules are centrally configured');
select is((select count(*) from app_private.unit_definitions where unit_code = 'noble'), 1::bigint, 'noble unit is available for server-side village capture');

select ok((select relrowsecurity from pg_class where oid = 'public.alliances'::regclass), 'alliance RLS is enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.alliance_members'::regclass), 'membership RLS is enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.alliance_invitations'::regclass), 'invitation RLS is enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.diplomatic_relations'::regclass), 'diplomacy RLS is enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.private_messages'::regclass), 'private-message RLS is enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.alliance_messages'::regclass), 'alliance-message RLS is enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.multiplayer_notifications'::regclass), 'notification RLS is enabled');

select ok(not has_table_privilege('authenticated', 'public.private_messages', 'SELECT'), 'clients cannot directly read private messages');
select ok(not has_table_privilege('authenticated', 'public.alliance_members', 'UPDATE'), 'clients cannot directly change alliance roles');
select ok(not has_table_privilege('authenticated', 'public.alliances', 'INSERT'), 'clients cannot directly create alliances');
select ok(has_table_privilege('authenticated', 'public.multiplayer_notifications', 'SELECT'), 'clients can subscribe to their RLS-filtered notifications');
select ok(not has_table_privilege('authenticated', 'public.multiplayer_notifications', 'INSERT'), 'clients cannot forge notifications');

select ok(has_function_privilege('authenticated', 'public.create_alliance(text,text,text)', 'EXECUTE'), 'authenticated players can create alliances via RPC');
select ok(not has_function_privilege('anon', 'public.create_alliance(text,text,text)', 'EXECUTE'), 'anonymous players cannot create alliances');
select ok(not has_function_privilege('authenticated', 'public._notify_player(uuid,text)', 'EXECUTE'), 'clients cannot forge notification events');
select has_function('public', 'get_owned_villages', array[]::text[], 'owned villages are loaded via a server RPC');
select has_function('public', 'found_additional_village', array['uuid', 'text'], 'expansion uses a protected server RPC');
select has_function('public', 'get_player_rankings', array[]::text[], 'rankings are generated by a server RPC');
select has_function('public', 'capture_village_after_battle', array[]::text[], 'capture is integrated into battle resolution');

select ok(exists (
  select 1 from pg_trigger where tgname = 'troop_movement_capture_village' and not tgisinternal
), 'capturing a village is triggered only by server-resolved combat');
select ok(exists (
  select 1 from pg_publication_tables
  where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'multiplayer_notifications'
), 'safe notifications are published for realtime updates');

select * from finish();
rollback;
